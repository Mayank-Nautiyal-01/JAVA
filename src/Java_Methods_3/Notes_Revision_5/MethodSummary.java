/*
    =========================
    METHODS - COMPLETE REVISION
    =========================

    1. What is a Method?

       A reusable block of code
       that performs a specific task


    2. Method Declaration:

       returnType methodName(parameters) {
           // body
       }


    3. Types of Methods:

       a) System-defined
          → Built-in methods (Math, String, etc.)

       b) User-defined
          → Created by programmer

       c) Static method
          → Belongs to class, no object needed

       d) Final method
          → Cannot be overridden

       e) Abstract method
          → No body, must be implemented


    4. Method Overloading:

       - Same method name
       - Different parameters
       - Compile-time polymorphism


    5. Method Overriding:

       - Same method signature
       - Redefined in child class
       - Runtime polymorphism


    6. VarArgs:

       - Variable number of arguments
       - Internally array


    7. Key Differences:

       Overloading vs Overriding

       Overloading:
       - Same class
       - Compile-time
       - Parameters differ

       Overriding:
       - Parent-child
       - Runtime
       - Same signature


    8. Important Rules:

       - Return type required (except void)
       - Method must be called to execute
       - Static → no object needed
       - Final → no override
       - Abstract → must override


    9. One-line Ultimate Revision:

       "Method = reusable logic, polymorphism = flexibility in behavior"
*/