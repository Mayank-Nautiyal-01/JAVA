//What is a Class in Java?
//
//A Class is a blueprint or template used to define properties and behaviors of objects.
//In simple words:
//
//A class describes what an object will have and what it can do.
//Class	                 Object
//Car (design)	        BMW, Audi
//Student (structure)	    Rahul, Aman
//
//The class defines the structure, while objects are real instances created from it.

//Basic Structure of a Class-------------->
//class Student {
//
//    String name;
//    int age;
//
//    void study() {
//        System.out.println("Student is studying");
//    }
//
//}
//
//Here:
//
//name and age → properties
//
//study() → behavior
//
//Key Points About Classes=====
//
//1️ A class is a user-defined data type.
//2️ It contains variables (data) and methods (functions).
//        3️ It acts as a template for creating objects.
//        4️ A class does not occupy memory until objects are created.