//What is a String in Java?
//
//A String is a reference data type used to store text (sequence of characters).
//
//Example:
//
//String name = "Mayank";
//
//Here:
//
//String → class
//
//name → reference variable
//
//"Mayank" → String object
//
//Memory idea:
//
//Stack Memory          Heap Memory
//-------------         ----------------
//name  ------------->  "Mayank"

//-----extra -note
//String is a Class
//
//        In Java, String is not a primitive type.
//It is a class from java.lang package.
//
//Example:
//
//String str = new String("Hello");
//
//Here an object of String class is created.
